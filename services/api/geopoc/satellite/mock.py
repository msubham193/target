"""A provider that invents scenes and pixels, so everything else can be built and tested with no account and no network.

Its output is plainly synthetic: the collection id carries the real name only so the same checks apply, every record it
writes says `synthetic: true`, and the pixel values are a smooth deterministic pattern, not measurements. It never
imports
Earth Engine, opens a socket or reads a credential.
"""

import hashlib
from datetime import UTC, datetime, time, timedelta
from pathlib import Path
from typing import Any

import numpy as np
import rasterio
from rasterio.transform import from_origin

from geopoc.geo import convert
from geopoc.satellite.models import COLLECTION_ID, ExportPlan, SceneInfo, SceneQuery

REVISIT_DAYS = 5


def _unit(*parts: object) -> float:
    """A stable pseudo-random number in [0, 1) from the inputs."""
    digest = hashlib.sha256("|".join(map(str, parts)).encode()).digest()
    return int.from_bytes(digest[:8], "big") / 2**64


class MockProvider:
    name = "mock"
    synthetic = True

    def search(self, query: SceneQuery) -> list[SceneInfo]:
        query.check()
        scenes: list[SceneInfo] = []
        day = query.dates.start
        key = query.aoi.fingerprint()
        while day <= query.dates.end and len(scenes) < query.limit:
            cloud = round(_unit(key, day) * 100, 1)
            if query.max_cloud_percent is None or cloud <= query.max_cloud_percent:
                when = datetime.combine(day, time(5, 30), tzinfo=UTC)
                scenes.append(
                    SceneInfo(
                        scene_id=f"{COLLECTION_ID}/{when:%Y%m%dT%H%M%S}_MOCK_T{key[:5].upper()}",
                        collection=COLLECTION_ID,
                        acquisition_time=when,
                        cloud_percent=cloud,
                        tile=f"T{key[:5].upper()}",
                        processing_baseline="05.11",
                    )
                )
            day += timedelta(days=REVISIT_DAYS)
        return scenes

    def export_geotiff(self, plan: ExportPlan, scene: SceneInfo, destination: Path) -> dict[str, Any]:
        west, south, east, north = plan.aoi.bounds
        # Same policy as every other conversion. The plan's CRS is the WGS 84 UTM zone chosen for the AOI: exact.
        start = convert.from_geographic(plan.crs, west, north)
        x0, y0 = float(start.x), float(start.y)
        rows, cols = np.mgrid[0 : plan.height_px, 0 : plan.width_px]
        seed = _unit(scene.scene_id, plan.aoi.fingerprint())
        bands = [
            (800 + 4000 * (0.5 + 0.5 * np.sin((rows / 37 + cols / 53) + seed * 6.28 + i))).astype("uint16")
            for i, _ in enumerate(plan.bands)
        ]
        # mode "x": refuse to overwrite anything that exists
        with open(destination, "xb"):
            pass
        with rasterio.open(
            destination,
            "w",
            driver="GTiff",
            width=plan.width_px,
            height=plan.height_px,
            count=len(plan.bands),
            dtype="uint16",
            crs=plan.crs,
            transform=from_origin(x0, y0, plan.scale_m, plan.scale_m),
        ) as dst:
            for index, (name, data) in enumerate(zip(plan.bands, bands, strict=True), start=1):
                dst.write(data, index)
                dst.set_band_description(index, name)
        return {
            "request": {"mock": True, "scene_id": scene.scene_id, "bands": list(plan.bands), "scale_m": plan.scale_m},
            "attribution": ["SYNTHETIC DATA generated by geopoc.satellite.mock; not Copernicus Sentinel data."],
            "service": {"endpoint": None, "network": "none"},
        }
